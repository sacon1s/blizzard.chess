# Собирает public/puzzles.json из файлов генератора (*.jsonl): убирает повторы, укорачивает длинные решения
# (кроме матов) до двух ходов игрока и заново оценивает сложность. Запуск: python3 tools/build_puzzles.py <папка с .jsonl>
import sys, json, glob, hashlib
import chess

src = sys.argv[1]
seen, out = set(), []
for f in sorted(glob.glob(src.rstrip('/') + '/*.jsonl')):
    for line in open(f):
        try:
            p = json.loads(line)
        except ValueError:
            continue
        moves = p['moves'].split()
        key = p['fen'].split(' ')[0] + moves[0]
        if key in seen:
            continue
        seen.add(key)
        themes = [t for t in p['themes'] if t not in ('oneMove', 'short', 'long')]
        mate = any(t.startswith('mateIn') for t in themes)
        n_old = len(moves) // 2
        if not mate and n_old > 2:
            moves = moves[:4]
        n = len(moves) // 2
        b = chess.Board(p['fen'])
        b.push(chess.Move.from_uci(moves[0]))
        cap = p.get('cap')
        if cap is None:
            cap = b.is_capture(chess.Move.from_uci(moves[1]))
        d = p.get('d')
        if d is None:  # старые записи: глубину восстанавливаем по прежней формуле рейтинга
            d = round((p['rating'] - 450 - 170 * (n_old - 1) - (0 if cap else 120)) / 140)
        d = max(1, min(11, d))
        pid = hashlib.sha1((p['fen'] + p['moves']).encode()).hexdigest()[:6]
        jitter = int(pid[:2], 16) % 81 - 40
        r = 400 + 80 * d + 320 * (n - 1) + (0 if cap else 150) + jitter
        if mate and n == 1:
            r = min(r, 650)
        r = max(400, min(2400, r))
        themes.append('oneMove' if n == 1 else 'short' if n == 2 else 'long')
        out.append([pid, p['fen'], ' '.join(moves), r, ' '.join(themes)])
out.sort(key=lambda x: x[3])
json.dump({'license': 'Puzzles generated by Blizzard Chess from games between Blizzard bots.', 'puzzles': out},
          open('public/puzzles.json', 'w'), separators=(',', ':'))
print(len(out), 'puzzles')
